# -*- coding: utf-8 -*-
"""P5: README 的规模数字必须可核对 —— 手写数字必然腐烂。

审计实测（2026-10-15）：README 写「技能模块 50 / 行为卡片 42 / ~2500 文件 / ~25 MB」，
实际是 57 张顶层技能（另有 6 个嵌套 SKILL.md）、10 张在役卡、3083 个跟踪文件 / 43.0 MB。
四个数全错。START-HERE.md 又写「50 个技能（46 顶层 + 4 community wrapper）」——
同一仓库两份口径，且都与代码不符。

修法不是改数字（改了还会烂），而是：
  1. README 的规模表由本门生成的核对行背书，数字不作为事实由人维护；
  2. 本门每次运行重新计算，核对 README 里那行是否与实际一致。
"""
from __future__ import annotations

import argparse
import glob
import io
import json
import os
import re
import subprocess
from pathlib import Path

HERE = os.path.dirname(os.path.abspath(__file__))
SKILLS_ROOT = os.path.dirname(HERE)
PKG_ROOT = os.path.dirname(SKILLS_ROOT)
REPO_ROOT = os.path.dirname(PKG_ROOT)
README_PATH = os.path.join(REPO_ROOT, "README.md")


def _read(p):
    try:
        with io.open(p, encoding="utf-8-sig", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _walk_files():
    """遍历目录树取文件清单（无 git 时的回退）。

    排除项与 `.gitignore` 的运行时目录同源；只按**相对仓根**的段比，
    免得 runner 的 `/home/runner/work/...` 里那个 `work` 段把整棵树误伤。
    """
    skip_parts = {".git", "__pycache__", "node_modules", ".hub", ".candidates",
                  ".worktrees", "work"}
    out: list[str] = []
    for root, dirs, files in os.walk(REPO_ROOT):
        rel_root = Path(root).relative_to(REPO_ROOT)
        dirs[:] = [d for d in dirs if d not in skip_parts]
        if set(rel_root.parts) & skip_parts:
            continue
        for f in files:
            if f.endswith(".pyc"):
                continue
            out.append(str(rel_root / f).replace(os.sep, "/"))
    return sorted(out)


def tracked_files() -> list[str]:
    """仓库里「被跟踪」的文件清单。

    ★ 2026-10-17：原来只用 `git ls-files`。而 `tests/community/test-ci-negative-controls.py`
    的基线要求「**未改动的无 .git 副本**必须全绿」（spec 17.18 的发布包 run-skin）——
    在那个副本里 `git ls-files` 返回空，于是 tracked_files=0 / tracked_mb=0.0，
    门判红 → 基线不绿 → 整套负控失效（CI 上实测 `baseline ... green: False`）。
    git 不可用时回退到遍历目录树；两条路都不通才返回空（那时下面的 0 检查会判红）。
    """
    try:
        out = subprocess.run(["git", "-C", REPO_ROOT, "ls-files", "-z"],
                             capture_output=True, check=False, timeout=120).stdout
    except (OSError, subprocess.SubprocessError):
        out = b""
    files = [x.decode("utf-8") for x in out.split(b"\0") if x]
    if files:
        return files
    return _walk_files()


def _tracked_blob_bytes(files):
    """按 git 里**存储的** blob 大小求和 —— 与工作树的换行符无关。

    ★ 2026-10-17：原来用 os.path.getsize 逐文件求和。Windows 工作树是 CRLF、
    Linux/CI 检出是 LF（.gitattributes 归一化），同一次提交在两边量出的
    tracked_mb 差 0.1 MB —— 于是这个数字**不可能同时在两个平台上正确**：
    CI 上实测 `README scale 行 tracked_mb=43.6，实际 43.5` 永久红。
    改用 HEAD 的 blob 大小（仓库里实际存的字节），两边一致。
    工作树里有、HEAD 里没有的（新暂存文件）回退到 getsize。
    **无 git 的发布副本**里拿不到 blob 大小，全部回退到 on-disk 尺寸
    （那正是「包里的字节」；换行符会让末位可能差 0.1，属该形态的已知边界）。
    """
    sizes: dict[str, int] = {}
    try:
        out = subprocess.run(
            ["git", "-C", REPO_ROOT, "ls-tree", "-r", "-l", "-z", "HEAD"],
            capture_output=True, check=False, timeout=120).stdout
    except (OSError, subprocess.SubprocessError):
        out = b""
    for rec in out.split(b"\0"):
        if not rec:
            continue
        meta, _, path = rec.partition(b"\t")
        parts = meta.split()
        if len(parts) >= 4 and parts[1] == b"blob":
            try:
                sizes[path.decode("utf-8", "surrogateescape")] = int(parts[3])
            except ValueError:
                continue
    total = 0
    for rel in files:
        if rel in sizes:
            total += sizes[rel]
            continue
        try:
            total += os.path.getsize(os.path.join(REPO_ROOT, rel))
        except OSError:
            continue
    return total


def actual_numbers():
    """全部由文件系统 / git 现算，不读任何文档。"""
    # 顶层技能 = <skills>/<name>/SKILL.md
    top = [d for d in os.listdir(SKILLS_ROOT)
           if os.path.isfile(os.path.join(SKILLS_ROOT, d, "SKILL.md"))]
    # 嵌套技能 = 距技能根 2 层及以上的 SKILL.md（community/*、pentest-tools/src-hunter 等）
    nested = []
    for sp in glob.glob(os.path.join(SKILLS_ROOT, "**", "SKILL.md"), recursive=True):
        rel = os.path.relpath(sp, SKILLS_ROOT).replace(os.sep, "/")
        if rel.count("/") >= 2:
            nested.append(rel)
    # 卡片 = 三个池子（base / guest / hub）里的 .md
    cards_dir = os.path.join(REPO_ROOT, "kernel", "04-console", "cards")
    active = 0
    for pool in ("base", "guest", "hub"):
        p = os.path.join(cards_dir, pool)
        if os.path.isdir(p):
            active += len([f for f in os.listdir(p) if f.endswith(".md")])
    # 跟踪文件与体积
    files = tracked_files()
    total_bytes = _tracked_blob_bytes(files)
    return {
        "skills_top": len(top),
        "skills_nested": len(nested),
        "nested_paths": sorted(nested),
        "cards_active": active,
        "tracked_files": len(files),
        "tracked_mb": round(total_bytes / 1024 / 1024, 1),
    }


def scale_line(n):
    return ("<!-- scale: generated by skills/tests/check-readme-scale.py; do not hand-edit. "
            "skills_top={skills_top} skills_nested={skills_nested} "
            "cards_active={cards_active} tracked_files={tracked_files} "
            "tracked_mb={tracked_mb} -->").format(**n)


def check():
    n = actual_numbers()
    errs = []
    text = _read(README_PATH)
    if "scale: generated by" not in text:
        errs.append("README.md 缺少 scale 核对行（应在「## 规模」节内）——"
                    "手写规模数字已实测全部腐烂（P5）。请插入这一行：")
        errs.append("    " + scale_line(n))
        return errs, n
    m = re.search(r"<!-- scale: generated by[^>]*-->", text)
    got = m.group(0) if m else ""
    nums_now = dict(re.findall(r"(\w+)=([0-9.]+)", got))
    for key in ("skills_top", "skills_nested", "cards_active", "tracked_files", "tracked_mb"):
        have = nums_now.get(key)
        want = str(n[key])
        if have is None:
            errs.append("README scale 行缺字段 %s（应为 %s）" % (key, want))
        elif have != want:
            errs.append("README scale 行 %s=%s，实际 %s（README 手写数字腐烂了）" % (key, have, want))
    return errs, n


def check_table_dup() -> list[str]:
    """README 展示表里不得再出现手写的 scale 数字（第二份数字源，会腐烂）。"""
    text = _read(README_PATH)
    bad: list[str] = []
    pats = [
        (r"\|\s*技能模块\s*\|\s*\d+", "技能模块"),
        (r"\|\s*行为卡片\s*\|\s*\d+", "行为卡片"),
        (r"\|\s*本仓库\s*\|\s*\d+", "本仓库"),
    ]
    for pat, what in pats:
        for m in re.finditer(pat, text):
            bad.append(f"README 表格 {what} 行是手写数字（与 scale 行重复）：{m.group(0)[:50]!r}")
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--emit", action="store_true", help="只打印应插入 README 的核对行")
    a = ap.parse_args(argv)

    errs, n = check()
    errs += check_table_dup()
    if a.emit:
        print(scale_line(n))
        return 0
    if a.json:
        print(json.dumps({"errors": errs, "actual": n}, ensure_ascii=False, indent=2))
    elif errs:
        print("check-readme-scale: FAIL（%d 项）" % len(errs))
        for e in errs:
            print("  " + e)
    else:
        print("check-readme-scale: PASS（README 规模数字与现算一致：技能 %d 顶层 + %d 嵌套 / "
              "卡 %d / %d 文件 / %s MB）"
              % (n["skills_top"], n["skills_nested"], n["cards_active"],
                 n["tracked_files"], n["tracked_mb"]))
    return 20 if errs else 0


if __name__ == "__main__":
    raise SystemExit(main())
